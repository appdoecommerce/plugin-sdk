import fs from "fs"
import path from "path"

export async function prepareEnvironment(): Promise<void> {
  const cwd = process.cwd()
  const pluginsDir = path.join(cwd, "plugins")
  const envFile = path.join(cwd, ".env")

  console.log("🚀 Preparing development environment...\n")

  // Criar pasta plugins se não existir
  if (!fs.existsSync(pluginsDir)) {
    fs.mkdirSync(pluginsDir, { recursive: true })
    console.log("✅ Created plugins/ directory")
  } else {
    console.log("📁 plugins/ directory already exists")
  }

  // Criar arquivo .env se não existir
  if (!fs.existsSync(envFile)) {
    const envContent = `# AppDoEcommerce Environment Configuration
# Generated by appecom prepare

# Your store ID
APPECOM_STOREID=""

# Your secret key
APPECOM_SECRET=""
`
    fs.writeFileSync(envFile, envContent)
    console.log("✅ Created .env file")
  } else {
    console.log("📄 .env file already exists")
  }

  console.log("\n✨ Environment ready!")
  console.log("\nNext steps:")
  console.log("  1. Edit .env and fill in your APPECOM_STOREID and APPECOM_SECRET")
  console.log("  2. Run 'appecom make:plugin <name>' to create your first plugin")
}
